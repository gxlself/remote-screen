#!/usr/bin/env bash
# Exercise tools/ci/check-bindings.sh without cargo or a real ubrn install.
set -uo pipefail

HERE="$(cd -- "$(dirname -- "$0")" && pwd)" || exit 1
SCRIPT="$HERE/check-bindings.sh"
WORK="$(mktemp -d "${TMPDIR:-/tmp}/bindcheck-test.XXXXXX")" || exit 1
CASE=
GEN=
APP=
LIB=
FAKE_UBRN=
OUT=
ERR=
RC=0
PASSED=0
TOTAL=18

cleanup() {
    rm -rf -- "$WORK"
}
trap cleanup EXIT

ok() {
    PASSED=$((PASSED + 1))
    printf 'ok - %s\n' "$1"
}

not_ok() {
    printf 'not ok - %s\n' "$1"
    printf '  script status: %s\n' "$RC"
    if [[ -s "$OUT" ]]; then
        printf '  stdout:\n'
        sed -n '1,30p' "$OUT" | sed 's/^/    /'
    fi
    if [[ -s "$ERR" ]]; then
        printf '  stderr:\n'
        sed -n '1,30p' "$ERR" | sed 's/^/    /'
    fi
}

contains() {
    local file=$1 text=$2
    grep -Fq -- "$text" "$file" 2>/dev/null
}

new_case() {
    CASE="$(mktemp -d "$WORK/case.XXXXXX")" || exit 1
    GEN="$CASE/generated"
    APP="$CASE/fake-app"
    LIB="$CASE/fake.a"
    FAKE_UBRN="$CASE/fake-ubrn"
    OUT="$CASE/stdout"
    ERR="$CASE/stderr"
    RC=0
    mkdir -p "$GEN/ts" "$GEN/cpp" \
        "$APP/src/native/generated" "$APP/cpp/generated" \
        "$APP/node_modules/.bin" "$APP/artifacts"
    : >"$LIB"
}

write_generated() {
    cat >"$GEN/ts/rs_mobile.ts" <<'EOF'
export const answer = 42;
// generated by the fixture
EOF
    cat >"$GEN/ts/rs_mobile-ffi.ts" <<'EOF'
export const ffi = true;
EOF
    cat >"$GEN/cpp/rs_mobile.hpp" <<'EOF'
#pragma once
#include <cstdint>

uint64_t value();
EOF
    cat >"$GEN/cpp/rs_mobile.cpp" <<'EOF'
#include "rs_mobile.hpp"
#include <cstdint>

// generated comment
void f(uint64_t a,
     uint64_t b) {
    (void)a;
    (void)b;
    const char *text = "a//b";
    (void)text;
}

char quote() { return '"'; }
/* tail comment */
int after_quote() { return 7; }
EOF
}

copy_generated_to_repo() {
    cp -R -- "$GEN/ts/." "$APP/src/native/generated/"
    cp -R -- "$GEN/cpp/." "$APP/cpp/generated/"
}

seed() {
    new_case
    write_generated
    copy_generated_to_repo
    printf '#!/usr/bin/env bash\n' >"$APP/node_modules/.bin/prettier"
    chmod 755 "$APP/node_modules/.bin/prettier"
    cat >"$FAKE_UBRN" <<'EOF'
#!/usr/bin/env bash
set -uo pipefail
if [[ ${FAKE_UBRN_FAIL:-0} == 1 ]]; then
    printf 'fake ubrn: requested failure\n' >&2
    exit 1
fi
ts_dir=
cpp_dir=
library=
while (($#)); do
    case "$1" in
        --ts-dir) ts_dir=$2; shift 2 ;;
        --cpp-dir) cpp_dir=$2; shift 2 ;;
        *) library=$1; shift ;;
    esac
done
if [[ -z $ts_dir || -z $cpp_dir || -z $library ]]; then
    printf 'fake ubrn: missing generated arguments\n' >&2
    exit 1
fi
if [[ ! -d ${FAKE_GEN:-}/ts || ! -d ${FAKE_GEN:-}/cpp ]]; then
    printf 'fake ubrn: FAKE_GEN is incomplete\n' >&2
    exit 1
fi
mkdir -p -- "$ts_dir" "$cpp_dir"
cp -R -- "$FAKE_GEN/ts/." "$ts_dir/"
cp -R -- "$FAKE_GEN/cpp/." "$cpp_dir/"
EOF
    chmod 755 "$FAKE_UBRN"
}

run_case() {
    local fail=${FAKE_UBRN_FAIL_OVERRIDE:-0}
    local ubrn=${RS_UBRN_OVERRIDE:-$FAKE_UBRN}
    env RS_APP_ROOT="$APP" RS_UBRN="$ubrn" RS_BINDINGS_LIB="$LIB" \
        FAKE_GEN="$GEN" FAKE_UBRN_FAIL="$fail" \
        "$SCRIPT" "$@" >"$OUT" 2>"$ERR"
    RC=$?
}

run_case_without_ubrn() {
    local fail=${FAKE_UBRN_FAIL_OVERRIDE:-0}
    env RS_APP_ROOT="$APP" RS_BINDINGS_LIB="$LIB" \
        FAKE_GEN="$GEN" FAKE_UBRN_FAIL="$fail" \
        "$SCRIPT" "$@" >"$OUT" 2>"$ERR"
    RC=$?
}

repo_hash() {
    (
        cd -- "$APP" || exit 1
        for directory in src/native/generated cpp/generated; do
            [[ -d $directory ]] || continue
            find "$directory" -type f -print0
        done | sort -z | xargs -0 -r sha256sum
    )
}

repo_unchanged() {
    local before=$1
    [[ "$(repo_hash)" == "$before" ]]
}

write_whitespace_variant() {
    cat >"$APP/cpp/generated/rs_mobile.cpp" <<'EOF'
#include "rs_mobile.hpp"
#include <cstdint>

void f(uint64_t a, uint64_t b) { /* handle */
    (void)a;
    (void)b;
    const char *text = "a//b";
    (void)text;
}

char quote() { return '"'; }
int after_quote() { return 7; }
EOF
}

test_1_exact() {
    local name='exact generated tree matches'
    seed
    local before
    before=$(repo_hash)
    run_case
    if ((RC == 0)) && contains "$OUT" 'BINDINGS OK (ts=2 files, cpp=2 files)' && repo_unchanged "$before"; then
        ok "$name"
    else
        not_ok "$name"
    fi
}

test_2_ts_content() {
    local name='TS content change is stale'
    seed
    sed -i 's/answer = 42/answer = 43/' "$APP/src/native/generated/rs_mobile.ts"
    local before
