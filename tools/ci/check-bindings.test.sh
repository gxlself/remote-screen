    if ((RC == 1)) && contains "$OUT" 'STALE content src/native/generated/rs_mobile.ts' &&
        contains "$OUT" '+++' && repo_unchanged "$before"; then
        ok "$name"
    else
        not_ok "$name"
    fi
}

