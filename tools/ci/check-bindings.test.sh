test_13_cleanup_and_keep() {
    local name='staging cleanup and --keep'
    seed
    local before
    before=$(repo_hash)
    run_case
    local first_rc=$RC
    local leftovers
    leftovers=$(find "$APP/artifacts" -mindepth 1 -maxdepth 1 -name 'bindcheck.*' -print)
    run_case --keep
    local second_rc=$RC
    local kept
    kept=$(sed -n 's/^kept staging directory: //p' "$OUT")
    if ((first_rc == 0)) && [[ -z $leftovers ]] && ((second_rc == 0)) &&
        [[ -n $kept && -d $kept ]] && repo_unchanged "$before"; then
        rm -rf -- "$kept"
        ok "$name"
    else
        not_ok "$name"
    fi
}

test_14_repo_never_modified() {
